/**
 * Настройка отпечатка нативной части.
 *
 * Версия приложения поднимается на каждом попадании изменений в main, но на
 * нативную часть она не влияет — это строка в манифесте. По умолчанию
 * @expo/fingerprint считает её частью отпечатка, и тогда каждый подъём
 * версии рвал бы связь с уже установленными сборками: обновление по воздуху
 * ушло бы в новый runtimeVersion, а телефон остался бы на старом и молча
 * ничего не получил.
 *
 * ExpoConfigVersions выбрасывает из подсчёта version, versionCode и
 * buildNumber и оставляет всё остальное: модули, разрешения, иконки,
 * плагины.
 *
 * PackageJsonScriptsAll выбрасывает npm-скрипты: на сам APK они не влияют,
 * а добавленный скрипт линтера иначе требовал бы внеплановой сборки.
 *
 * Важно: если в package.json появятся хуки сборки EAS (eas-build-pre-install,
 * eas-build-post-install и подобные), скип надо снять — такой скрипт на APK
 * влияет напрямую.
 */
module.exports = {
  sourceSkips: ['ExpoConfigVersions', 'PackageJsonScriptsAll'],
};
